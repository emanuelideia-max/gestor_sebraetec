-- Gestor SEBRAETEC — schema do banco (Supabase / PostgreSQL)
-- Rode este arquivo uma vez no SQL Editor do projeto Supabase.
-- As tabelas de referência (cidades e etapas) são preenchidas pelo próprio app no primeiro acesso.

create table if not exists cidades (
    id           bigint generated by default as identity primary key,
    codigo_ibge  integer unique not null,
    nome         text not null,
    mesorregiao  text
);

create table if not exists etapas_status (
    id           integer primary key,          -- 1..21, na ordem do fluxo
    nome         text not null,
    responsavel  text
);

create table if not exists fornecedores (
    id         bigint generated by default as identity primary key,
    nome       text not null unique,
    cnpj       text,
    contato    text,
    email      text,
    telefone   text,
    created_at timestamptz default now()
);

create table if not exists clientes (
    id         bigint generated by default as identity primary key,
    nome       text not null,
    categoria  text,
    cidade_id  bigint references cidades(id),
    documento  text,
    contato    text,
    email      text,
    telefone   text,
    created_at timestamptz default now()
);

create table if not exists consultorias (
    id                    bigint generated by default as identity primary key,
    acao                  text default 'Sebraetec',
    inicio_processamento  date,
    area                  text,
    cliente_id            bigint references clientes(id),
    cidade_id             bigint references cidades(id),
    fornecedor_id         bigint references fornecedores(id),
    ficha_tecnica         text,
    valor_total           numeric(12,2) default 0,
    valor_hora            numeric(10,2) default 0,
    carga_horaria         numeric(8,1) default 0,
    subsidio              numeric(12,2) default 0,
    contrapartida         numeric(12,2) default 0,
    status_id             integer references etapas_status(id) default 1,
    status_desde          date default current_date,
    data_inicio           date,
    data_fim              date,
    observacoes           text,
    created_at            timestamptz default now()
);

create table if not exists historico_status (
    id              bigint generated by default as identity primary key,
    consultoria_id  bigint references consultorias(id) on delete cascade,
    status_id       integer references etapas_status(id),
    data            date default current_date,
    usuario         text,
    observacao      text,
    created_at      timestamptz default now()
);

create table if not exists agenda (
    id              bigint generated by default as identity primary key,
    titulo          text not null,
    data            date not null,
    hora            text,
    tipo            text,
    local           text,
    descricao       text,
    consultoria_id  bigint references consultorias(id) on delete set null,
    created_at      timestamptz default now()
);

create table if not exists lembretes (
    id              bigint generated by default as identity primary key,
    titulo          text not null,
    data            date not null,
    prioridade      text default 'Normal',
    concluido       boolean default false,
    consultoria_id  bigint references consultorias(id) on delete set null,
    created_at      timestamptz default now()
);

create table if not exists configuracoes (
    id     integer primary key,             -- sempre 1: configurações da plataforma
    dados  jsonb not null default '{}'::jsonb
);

create index if not exists idx_consultorias_status on consultorias(status_id);
create index if not exists idx_historico_consultoria on historico_status(consultoria_id);

-- Segurança: só usuários autenticados (login do app) leem e escrevem.
do $$
declare t text;
begin
  foreach t in array array['cidades','etapas_status','fornecedores','clientes','consultorias',
                           'historico_status','agenda','lembretes','configuracoes'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "autenticados_%s" on %I', t, t);
    execute format('create policy "autenticados_%s" on %I for all to authenticated using (true) with check (true)', t, t);
  end loop;
end $$;
